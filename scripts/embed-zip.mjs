// Bundles private/meta-ads-advanced.zip into the server code as base64, so the
// paid file can be served and emailed on Cloudflare Workers (no file system).
// Runs before every build (npm "prebuild"). The output is only imported by
// server code (lib/advanced-zip.ts), never sent to the browser.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const zip = readFileSync(join(root, "private", "meta-ads-advanced.zip"))
const out = join(root, "lib", "generated", "advanced-zip.ts")
mkdirSync(dirname(out), { recursive: true })
writeFileSync(
  out,
  `// Generated by scripts/embed-zip.mjs from private/meta-ads-advanced.zip. Don't edit.\n// Server-only: import through lib/advanced-zip.ts.\nexport const ADVANCED_ZIP_BASE64 =\n  "${zip.toString("base64")}"\n`
)
console.log(`embedded ${zip.length} bytes → lib/generated/advanced-zip.ts`)
